"""Test generation backends.

- DeterministicGenerator: runs the changed function on mined boundary inputs, keeps a small set of
  cases that maximises line coverage and outcome variety, and writes them as pytest tests.
- LLMGenerator (see testgen_llm.py): asks an LLM for tests, then validates them by execution.
"""
from __future__ import annotations

import ast
from dataclasses import dataclass, field

from .codemap import FunctionInfo
from .inputs import generate_cases
from .runner import call_harness

NOISE_EXCEPTIONS = {"TypeError", "AttributeError", "RecursionError"}
MAX_SELECTED = 14


@dataclass
class GeneratedTests:
    function: str
    filename: str
    code: str
    n_tests: int
    backend: str
    notes: list[str] = field(default_factory=list)
    disagreements: list[str] = field(default_factory=list)  # LLM expectations the code does not meet


def supported(fn: FunctionInfo) -> bool:
    return not fn.is_method and "<locals>" not in fn.name and fn.is_public


def observe(root, fn: FunctionInfo, cases: list[list]) -> list[tuple[list, dict]]:
    results = call_harness(root, fn.module, fn.name, cases, trace_file=fn.path)
    return list(zip(cases, results))


def _numbers(args) -> list:
    out = []
    for a in args:
        if isinstance(a, (int, float)) and not isinstance(a, bool):
            out.append(a)
    return out


def select(observed: list[tuple[list, dict]], fn: FunctionInfo, cap: int = MAX_SELECTED) -> list[tuple[list, dict]]:
    usable = []
    for args, res in observed:
        if res.get("status") == "return" and res.get("literal"):
            usable.append((args, res))
        elif res.get("status") == "raise" and res.get("exc") not in NOISE_EXCEPTIONS:
            usable.append((args, res))
    chosen: list[tuple[list, dict]] = []
    covered: set[int] = set()
    remaining = list(usable)
    # 1) greedy line coverage
    while remaining and len(chosen) < cap:
        best = max(remaining, key=lambda x: len(set(x[1].get("lines", [])) - covered))
        gain = set(best[1].get("lines", [])) - covered
        if not gain:
            break
        chosen.append(best)
        covered |= gain
        remaining.remove(best)

    def sig(res):
        return res.get("repr") if res["status"] == "return" else f"raise:{res.get('exc')}"
    # 2) one example of every distinct outcome
    seen = {sig(r) for _, r in chosen}
    for item in list(remaining):
        if len(chosen) >= cap:
            break
        if sig(item[1]) not in seen:
            chosen.append(item)
            seen.add(sig(item[1]))
            remaining.remove(item)
    # 3) boundary hits: inputs equal to (then next to) constants the code compares against
    mined = {float(n) for n in fn.literals.get("num", [])}
    exact = [x for x in remaining if any(float(n) in mined for n in _numbers(x[0]))]
    for item in exact:
        if len(chosen) >= cap:
            break
        chosen.append(item)
        remaining.remove(item)
    near = set()
    for n in mined:
        near |= {round(n - 1, 6), round(n + 1, 6), round(n - 0.01, 6), round(n + 0.01, 6)}
    for item in [x for x in remaining if any(round(float(n), 6) in near for n in _numbers(x[0]))]:
        if len(chosen) >= cap:
            break
        chosen.append(item)
        remaining.remove(item)
    return chosen


def _expected_expr(res: dict) -> tuple[str, bool]:
    value = ast.literal_eval(res["repr"])

    def has_float(v):
        if isinstance(v, float):
            return True
        if isinstance(v, (list, tuple)):
            return any(has_float(x) for x in v)
        if isinstance(v, dict):
            return any(has_float(x) for x in v.values())
        return False

    def numeric_only(v):
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            return True
        if isinstance(v, (list, tuple)):
            return all(numeric_only(x) for x in v)
        if isinstance(v, dict):
            return all(numeric_only(x) for x in v.values())
        return False
    approx = has_float(value) and numeric_only(value)
    return repr(value), approx


def render(fn: FunctionInfo, chosen: list[tuple[list, dict]]) -> tuple[str, int]:
    name = fn.name
    returns = [(a, r) for a, r in chosen if r["status"] == "return"]
    raises = [(a, r) for a, r in chosen if r["status"] == "raise"]
    imports = {f"from {fn.module} import {name}"}
    exc_names = {}
    for _, r in raises:
        if r.get("exc_module") in (None, "builtins"):
            exc_names[r["exc"]] = r["exc"]
        else:
            imports.add(f"from {r['exc_module']} import {r['exc']}")
            exc_names[r["exc"]] = r["exc"]
    lines = [f'"""Tests generated by QualityLens for {fn.qualname}.',
             "",
             "Expected values were recorded from the implementation at the analysed commit (characterization",
             'tests). Review them: if the current behaviour is wrong, these tests lock the bug in."""',
             "import pytest", "", *sorted(imports), "", ""]
    n = 0
    if returns:
        rows = []
        for args, r in returns:
            expr, approx = _expected_expr(r)
            rows.append(f"    ({tuple(args)!r}, {expr}, {approx}),")
        lines += ["@pytest.mark.parametrize(\"args, expected, approx\", [", *rows, "])",
                  f"def test_{name}_returns(args, expected, approx):",
                  f"    result = {name}(*args)",
                  "    assert result == (pytest.approx(expected) if approx else expected)", "", ""]
        n += len(returns)
    if raises:
        rows = [f"    ({tuple(a)!r}, {exc_names[r['exc']]})," for a, r in raises]
        lines += ["@pytest.mark.parametrize(\"args, error\", [", *rows, "])",
                  f"def test_{name}_raises(args, error):",
                  "    with pytest.raises(error):",
                  f"        {name}(*args)", "", ""]
        n += len(raises)
    return "\n".join(lines).rstrip() + "\n", n


class DeterministicGenerator:
    name = "deterministic"

    def generate(self, root, fn: FunctionInfo, context: dict | None = None) -> GeneratedTests | None:
        if not supported(fn):
            return None
        observed = observe(root, fn, generate_cases(fn))
        chosen = select(observed, fn)
        if not chosen:
            return None
        code, n = render(fn, chosen)
        fname = f"test_ql_{fn.module.replace('.', '_')}_{fn.name}.py"
        return GeneratedTests(function=fn.qualname, filename=fname, code=code, n_tests=n, backend=self.name,
                              notes=[f"{len(observed)} inputs executed, {n} kept"])
